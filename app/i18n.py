_current = "en"


def set_language(code: str) -> None:
    global _current
    _current = code if code in TRANSLATIONS else "en"


def current_language() -> str:
    return _current


def is_rtl() -> bool:
    return _current in RTL_LANGUAGES


def tr(key: str, **kwargs) -> str:
    text = TRANSLATIONS.get(_current, {}).get(key) or TRANSLATIONS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text
